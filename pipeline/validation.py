"""Validate gold against officially published UDISE+ figures.

The SQL in sql/validation/ computes the published indicators from gold; this module
lines them up with reference/official_totals.json and writes
reports/validation.csv and reports/validation.md (official, ours, difference, % difference).
Indicators with no official figure (e.g. 2025-26) are listed for information.
"""
from pathlib import Path

import duckdb
import pandas as pd

from . import config as C

VALIDATION_SQL = C.ROOT / "sql" / "validation"


def compute_indicators(gold_db: Path = C.GOLD_DB) -> pd.DataFrame:
    con = duckdb.connect(str(gold_db), read_only=True)
    try:
        frames = [con.execute(p.read_text(encoding="utf-8")).df()
                  for p in sorted(VALIDATION_SQL.glob("*.sql"))]
    finally:
        con.close()
    return pd.concat(frames, ignore_index=True)


def compare(ours: pd.DataFrame, official: dict[str, dict[str, int]]) -> pd.DataFrame:
    off = pd.DataFrame([{"year": y, "indicator": k, "official": v}
                        for y, vals in official.items() for k, v in vals.items()])
    out = ours.merge(off, on=["year", "indicator"], how="outer")
    out["ours"] = out.pop("value")
    out["difference"] = out["ours"] - out["official"]
    out["pct_difference"] = (out["difference"] / out["official"] * 100).round(3)
    out["result"] = out.apply(
        lambda r: "no official figure" if pd.isna(r["official"]) else
                  "missing in gold" if pd.isna(r["ours"]) else
                  "exact match" if r["difference"] == 0 else "differs", axis=1)
    return out[["year", "indicator", "official", "ours", "difference", "pct_difference", "result"]] \
        .sort_values(["year", "indicator"]).reset_index(drop=True)


def indian(n) -> str:
    """Format with Indian digit grouping, as in UDISE+ reports (1,63,64,187)."""
    if pd.isna(n):
        return ""
    sign, s = ("-" if n < 0 else ""), str(int(abs(n)))
    if len(s) <= 3:
        return sign + s
    head, tail = s[:-3], s[-3:]
    groups = []
    while len(head) > 2:
        groups.insert(0, head[-2:])
        head = head[:-2]
    return sign + ",".join(([head] if head else []) + groups + [tail])


def to_markdown(table: pd.DataFrame, source: str) -> str:
    checked = table[table["result"] != "no official figure"]
    exact = int((checked["result"] == "exact match").sum())
    lines = ["# Validation against official UDISE+ figures", "",
             "Generated by `pipeline/validation.py` from the gold database (`sql/validation/`).", "",
             f"Official figures: {source}", "",
             f"**{exact} of {len(checked)} published indicators match exactly.**", "",
             "| Year | Indicator | Official | Ours (gold) | Difference | % difference | Result |",
             "|---|---|---:|---:|---:|---:|---|"]
    for _, r in table.iterrows():
        pct = "" if pd.isna(r["pct_difference"]) else f"{r['pct_difference']:+.3f}"
        lines.append(f"| {r['year']} | {r['indicator']} | {indian(r['official'])} | {indian(r['ours'])} | "
                     f"{indian(r['difference'])} | {pct} | {r['result']} |")
    lines += ["", "Definitions: enrolment includes pre-primary (as published); `enrolment_classes_1_12` "
              "is what the analysis uses. A zero-enrolment school has no students at all, "
              "pre-primary included. Government = management groups marked government in "
              "`reference/management_codes.json`.", "", f"{C.SOURCE_NOTE}."]
    return "\n".join(lines) + "\n"


def validate(gold_db: Path = C.GOLD_DB, out_dir: Path = C.REPORTS_DIR,
             official: dict | None = None) -> dict:
    ref = C.load_reference("official_totals.json")
    official = official if official is not None else ref["totals"]
    table = compare(compute_indicators(gold_db), official)
    out_dir.mkdir(parents=True, exist_ok=True)
    table.to_csv(out_dir / "validation.csv", index=False)
    (out_dir / "validation.md").write_text(to_markdown(table, ref["source"]), encoding="utf-8")
    checked = table[table["result"] != "no official figure"]
    return {"indicators_checked": len(checked),
            "exact_matches": int((checked["result"] == "exact match").sum()),
            "max_abs_pct_difference": float(checked["pct_difference"].abs().max()) if len(checked) else None}
