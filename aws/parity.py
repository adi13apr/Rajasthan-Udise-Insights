"""Parity and reconciliation: the Athena lakehouse vs the local DuckDB pipeline.

    python -m aws.parity        -> reports/aws_parity.md and reports/aws_parity.json

Checks (any failure -> exit code 1):
  1. Official figures: the UDISE+ indicators computed on Athena gold (sql/athena/validation/)
     equal the published 2024-25 totals in reference/official_totals.json exactly. DuckDB gold
     is checked the same way.
  2. Fingerprint: the same SQL queries run on both engines and their results are compared cell
     by cell: row counts of every silver, quarantine and gold table; quarantined rows per rule;
     silver rows and warning flags per year; facilities, enrolment (by stage, gender and social
     category), teachers and int_school_year per district and year; dim_school per district;
     SCD2 district moves; both marts; the official indicators. Whole numbers (counts, sums,
     keys) must be equal exactly; ratio columns may differ by at most 0.001 (the marts round to
     3 decimals and engines can round a .xxx5 differently).
  3. Data tests: every check in sql/athena/tests (Athena) and sql/tests (DuckDB) returns 0.

The queries and the comparison are the ones spark/parity.py uses for PySpark vs DuckDB
(spark.parity.fingerprint_queries / compare): one definition of "the same result" for every
engine. Only the official-indicators query differs per engine (Athena has no UNPIVOT).

Reads DuckDB gold (data/gold/udise.duckdb), silver and quarantine read-only, and runs read-only
SELECTs in Athena (workgroup udise-wg). The report holds district-level aggregates only.
"""
import argparse
import json
import sys
import time
from datetime import datetime, timezone

from pipeline import config as C
from spark.checks import check_official
from spark.parity import RATIO_TOLERANCE, compare, duckdb_fingerprint, fingerprint_queries, fmt, normalise
from spark.parity import validation_sql as duckdb_validation_sql

from . import settings as S
from .athena import Athena
from .athena_build import placeholders, run_tests
from .athena_build import validation_sql as athena_validation_sql

REPORT_MD = C.REPORTS_DIR / "aws_parity.md"
REPORT_JSON = C.REPORTS_DIR / "aws_parity.json"


def athena_fingerprint(ath: Athena, queries) -> dict:
    return {q.name: normalise(ath.query_df(q.sql, f"parity {q.name}")) for q in queries}


def write_report(results: dict, tests: dict, official: dict, timings: dict, athena_usage: dict) -> dict:
    mismatches = [m for r in results.values() for m in r["mismatches"]]
    ratio_diffs = [r["max_ratio_diff"] for r in results.values() if r["max_ratio_diff"] is not None]
    failed_tests = {e: [t for t in ts if t["failures"]] for e, ts in tests.items()}
    official_bad = {e: [o for o in rows if not o["match"]] for e, rows in official.items()}
    passed = not mismatches and not any(failed_tests.values()) and not any(official_bad.values())
    summary = {
        "passed": passed,
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "ratio_tolerance": RATIO_TOLERANCE,
        "queries": {n: {k: v for k, v in r.items() if k != "mismatches"} | {"mismatches": len(r["mismatches"])}
                    for n, r in results.items()},
        "cells_compared": sum(r["cells"] for r in results.values()),
        "mismatches": len(mismatches),
        "max_ratio_diff": max(ratio_diffs) if ratio_diffs else None,
        "data_tests": {e: {"checks": len(ts), "failed": len(failed_tests[e])} for e, ts in tests.items()},
        "official": official,
        "timings_seconds": timings,
        "athena": athena_usage,
        "mismatch_details": mismatches[:500],
    }
    lines = [
        "# Parity: Athena (AWS) vs DuckDB (local)", "",
        "Generated by `python -m aws.parity`. The same SQL queries (`spark/parity.py` fingerprint) run on "
        "the Athena tables built by `aws/athena_build.py` and on the local DuckDB pipeline's silver, "
        "quarantine and gold, and the results are compared cell by cell.", "",
        f"**Result: {'PASS' if passed else 'FAIL'}.** {summary['cells_compared']:,} cells compared, "
        f"{len(mismatches)} mismatches. Whole numbers must match exactly; ratio columns may differ by at most "
        f"{RATIO_TOLERANCE}. Largest ratio difference found: {fmt(summary['max_ratio_diff'])}.", "",
        "| Query | Rows matched | Cells compared | Mismatches | Largest ratio difference |",
        "|---|---:|---:|---:|---:|"]
    for n, r in results.items():
        lines.append(f"| {n} | {r['rows']:,} | {r['cells']:,} | {len(r['mismatches'])} | "
                     f"{fmt(r['max_ratio_diff']) if r['max_ratio_diff'] is not None else '-'} |")
    lines += ["", "## Data tests", "", "| Engine | Checks | Failed |", "|---|---:|---:|"]
    lines += [f"| {e} | {len(ts)} | {len(failed_tests[e])} |" for e, ts in tests.items()]
    lines += ["", "Athena runs the four DuckDB test files translated (`sql/athena/tests/`) plus two more: "
              "bronze rows = silver rows + quarantined rows, per dataset (in DuckDB that check is in "
              "`pipeline/silver.py`), and `_source_row` runs 1..n in every bronze file (the validator "
              "Lambda reads only file footers, so this check runs in Athena).", "",
              "## Official 2024-25 totals", "",
              "| Indicator | Official | Athena | DuckDB |", "|---|---:|---:|---:|"]
    for a, d in zip(official["Athena"], official["DuckDB"]):
        lines.append(f"| {a['year']} {a['indicator']} | {a['official']:,} | {fmt(a['ours'])}"
                     f"{'' if a['match'] else ' (differs)'} | {fmt(d['ours'])}{'' if d['match'] else ' (differs)'} |")
    lines += ["", "## Run", "", "| Step | Seconds |", "|---|---:|"]
    lines += [f"| {k} | {v} |" for k, v in timings.items()]
    lines += ["", f"Athena: {athena_usage['queries']} read-only queries, "
              f"{athena_usage['bytes_scanned'] / 1e6:.1f} MB scanned."]
    if mismatches:
        lines += ["", "## Mismatches", "", "| Query | Key | Column | DuckDB | Athena | Problem |",
                  "|---|---|---|---|---|---|"]
        for m in mismatches[:200]:
            lines.append(f"| {m['query']} | {m.get('key', '')} | {m.get('column', '')} | {fmt(m.get('duckdb'))} | "
                         f"{fmt(m.get('spark'))} | {m.get('problem', m.get('kind', '')).replace('Spark', 'Athena')} |")
    lines += ["", f"{C.SOURCE_NOTE}. District-level aggregates only."]
    REPORT_MD.parent.mkdir(parents=True, exist_ok=True)
    REPORT_MD.write_text("\n".join(lines) + "\n", encoding="utf-8")
    REPORT_JSON.write_text(json.dumps(summary, indent=2, default=str) + "\n", encoding="utf-8")
    return summary


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Athena vs DuckDB parity and official reconciliation")
    ap.add_argument("--profile", default=S.PROFILE)
    args = ap.parse_args(argv)
    if not C.GOLD_DB.exists():
        print(f"{C.display_path(C.GOLD_DB)} not found: run python run_pipeline.py first.")
        return 1

    timings = {}
    t0 = time.perf_counter()
    duck_queries = fingerprint_queries(duckdb_validation_sql())
    duck, duck_tests = duckdb_fingerprint(duck_queries)
    timings["duckdb: fingerprint + data tests"] = round(time.perf_counter() - t0, 1)

    t0 = time.perf_counter()
    ath = Athena(args.profile)
    athena = athena_fingerprint(ath, fingerprint_queries(athena_validation_sql()))
    athena_tests = run_tests(ath, placeholders(ath))
    timings["athena: fingerprint + data tests"] = round(time.perf_counter() - t0, 1)

    results = compare(duck_queries, duck, athena)   # same names, keys and tolerances
    official = {"Athena": check_official(athena["official_indicators"]),
                "DuckDB": check_official(duck["official_indicators"])}
    summary = write_report(results, {"Athena": athena_tests, "DuckDB": duck_tests}, official, timings,
                           ath.summary())
    exact = sum(o["match"] for o in official["Athena"])
    print(f"{'PASS' if summary['passed'] else 'FAIL'}: {summary['cells_compared']:,} cells compared, "
          f"{summary['mismatches']} mismatches; official {exact}/{len(official['Athena'])} exact on Athena; "
          f"report {C.display_path(REPORT_MD)}")
    return 0 if summary["passed"] else 1


if __name__ == "__main__":
    sys.exit(main())
