"""Write the bronze file contract the validator Lambda checks uploads against.

    python -m aws.make_contract     -> aws/bronze_validator/contract.json

For every local bronze file (data/bronze/<dataset>/year=<Y>/<file>.parquet) the contract
records the S3 key it is uploaded to, its dataset and year, its row count, and its exact
columns and types (in order). Files with the same columns share one schema entry, which keeps
the file small. Row counts are cross-checked against data/bronze/_state.json (written when
bronze was loaded); a difference stops the script.

The contract holds file names, column names and row counts only, no school data, so it is
committed. Regenerate it whenever bronze changes (new year, new download), then redeploy
(aws/deploy.sh): a file that is not in the contract is quarantined.
"""
import json
import sys
from pathlib import Path

import pyarrow.parquet as pq

from pipeline import config as C

from . import settings as S
from .upload_bronze import local_files, s3_key

CONTRACT = Path(__file__).with_name("bronze_validator") / "contract.json"
METADATA_COLUMNS = ["_source_file", "_source_row", "_district_file", "_year", "_ingested_at", "_run_id"]


def file_schema(path: Path) -> list[list[str]]:
    return [[f.name, str(f.type)] for f in pq.read_schema(path)]


def build_contract(bronze_dir: Path = C.BRONZE_DIR) -> dict:
    state = json.loads((bronze_dir / "_state.json").read_text(encoding="utf-8"))
    state_rows = {rec["bronze_file"]: rec["rows"] for rec in state["files"].values()}
    schemas: dict[str, list] = {}
    ids: dict[str, str] = {}
    files = {}
    for path in local_files(bronze_dir):
        rel = path.relative_to(bronze_dir).as_posix()
        rows = pq.read_metadata(path).num_rows
        if state_rows.get(rel) != rows:
            raise SystemExit(f"{rel}: {rows} rows in the file but {state_rows.get(rel)} in _state.json")
        cols = file_schema(path)
        missing = [c for c in METADATA_COLUMNS if c not in [n for n, _ in cols]]
        if missing:
            raise SystemExit(f"{rel}: metadata columns missing: {missing}")
        sig = json.dumps(cols)
        if sig not in ids:
            ids[sig] = f"s{len(ids) + 1}"
            schemas[ids[sig]] = cols
        dataset, part = rel.split("/")[:2]
        files[s3_key(path, bronze_dir)] = {"dataset": dataset, "year": part.split("=", 1)[1],
                                          "rows": rows, "schema": ids[sig]}
    return {
        "description": "Bronze file contract for the validator Lambda. Generated by "
                       "`python -m aws.make_contract` from data/bronze; do not edit by hand.",
        "bucket_prefix": S.BRONZE_PREFIX,
        "metadata_columns": METADATA_COLUMNS,
        "files": files,
        "schemas": schemas,
    }


def main() -> int:
    contract = build_contract()
    CONTRACT.write_text(json.dumps(contract, indent=1) + "\n", encoding="utf-8")
    rows = sum(f["rows"] for f in contract["files"].values())
    print(f"Wrote {C.display_path(CONTRACT)}: {len(contract['files'])} files, {rows:,} rows, "
          f"{len(contract['schemas'])} distinct schemas.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
